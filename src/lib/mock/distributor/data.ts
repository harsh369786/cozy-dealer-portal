export function computeDashboardStats(): DashboardStats {
  const active = dealers.filter((d) => d.active);
  const pending = seedOrders.filter((o) => o.status === "order_placed").length;
  const monthSales = dealers.reduce((s, d) => s + d.monthSales, 0);
  const prevMonth = dealers.reduce((s, d) => s + d.prevMonthSales, 0);
  return {
    totalDealers: dealers.length,
    activeDealers: active.length,
    ordersThisMonth: monthlySales[monthlySales.length - 1]!.orders,
    monthlySales: monthSales,
    pendingApprovals: pending,
    openComplaints: seedComplaints.filter(
      (c) => c.status === "pending" || c.status === "in_progress",
    ).length,
    rewardPointsGenerated: dealers.reduce((s, d) => s + d.rewardPoints, 0),
    salesGrowth: Math.round(((monthSales - prevMonth) / prevMonth) * 100),
    prevMonthSales: prevMonth,
  };
}
