// Backfill existing dealers to the standardized code format  FIRST4-PINCODE[-N].
//
// The legacy code is preserved in dealers.legacy_code (migration 0044 snapshots it). This script
// recomputes `code` for every dealer using the SAME rules as api/services/dealer-code.ts:
//   prefix  = first 4 letters (A–Z only) of store_name, uppercased (fallback "DLER")
//   pincode = the dealer's 6-digit pincode, else "000000"
//   dedup   = sequential numeric suffix (-1, -2, ...) so codes stay globally unique
//
// It reads the current dealers via `wrangler d1 execute ... --json`, computes the new codes in JS
// (letters-only + dedup can't be done in SQLite string functions), and writes an idempotent
// UPDATE .sql file. Nothing is changed unless you apply that file.
//
// Usage:
//   node scripts/backfill-dealer-codes.mjs            # local DB
//   node scripts/backfill-dealer-codes.mjs --remote   # remote (production) DB
// Then apply the generated file, e.g.:
//   wrangler d1 execute backrest-db --remote --config wrangler.toml --file scripts/dealer-codes.generated.sql

import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const OUTPUT = join(ROOT, "scripts", "dealer-codes.generated.sql");
const REMOTE = process.argv.includes("--remote");

function dealerCodePrefix(storeName) {
  const lettersOnly = String(storeName ?? "").replace(/[^A-Za-z]/g, "");
  return lettersOnly.slice(0, 4).toUpperCase() || "DLER";
}
function dealerCodePincode(pincode) {
  const digits = String(pincode ?? "").replace(/\D/g, "");
  return /^\d{6}$/.test(digits) ? digits : "000000";
}
function sqlStr(s) {
  return `'${String(s).replace(/'/g, "''")}'`;
}

function resolveWranglerRunner() {
  // `wrangler` is usually not on PATH in this project; it's run via a package manager.
  // Prefer bun (this repo's manager), then npx, then a bare wrangler as a last resort.
  const home = process.env.USERPROFILE || process.env.HOME || "";
  const bunExe = home ? join(home, ".bun", "bin", process.platform === "win32" ? "bun.exe" : "bun") : "bun";
  if (existsSync(bunExe)) return { cmd: bunExe, prefix: ["x", "wrangler"] };
  const npx = process.platform === "win32" ? "npx.cmd" : "npx";
  return { cmd: npx, prefix: ["wrangler"] };
}

function fetchDealers() {
  // wrangler prints JSON like: [ { results: [...] } ]
  const { cmd, prefix } = resolveWranglerRunner();
  const args = [
    ...prefix,
    "d1",
    "execute",
    "backrest-db",
    REMOTE ? "--remote" : "--local",
    "--config",
    "wrangler.toml",
    "--json",
    "--command",
    "SELECT id, store_name, pincode, code FROM dealers ORDER BY created_at",
  ];
  const out = execFileSync(cmd, args, { cwd: ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  // Strip any non-JSON preamble wrangler may print before the array.
  const start = out.indexOf("[");
  const parsed = JSON.parse(out.slice(start));
  const first = Array.isArray(parsed) ? parsed[0] : parsed;
  return first?.results ?? [];
}

function main() {
  const dealers = fetchDealers();
  // Deterministic order (creation order) so suffix assignment is stable across runs.
  const taken = new Set();
  const updates = [];

  for (const d of dealers) {
    const base = `${dealerCodePrefix(d.store_name)}-${dealerCodePincode(d.pincode)}`;
    let code = base;
    if (taken.has(code)) {
      let n = 1;
      while (taken.has(`${base}-${n}`)) n++;
      code = `${base}-${n}`;
    }
    taken.add(code);
    // legacy_code is set by migration 0044; keep the existing snapshot, only rewrite `code`.
    if (code !== d.code) {
      updates.push(`UPDATE dealers SET code = ${sqlStr(code)} WHERE id = ${sqlStr(d.id)};`);
    }
  }

  const parts = [
    "-- Generated by scripts/backfill-dealer-codes.mjs — standardized dealer codes (FIRST4-PINCODE[-N]).",
    "-- legacy_code preserved by migration 0044. Apply with:",
    "--   wrangler d1 execute backrest-db --remote --config wrangler.toml --file scripts/dealer-codes.generated.sql",
    ...updates,
  ];
  writeFileSync(OUTPUT, parts.join("\n") + "\n", { encoding: "utf8" });
  console.log(`Dealers: ${dealers.length}, codes to rewrite: ${updates.length}`);
  console.log(`Wrote ${OUTPUT}`);
}

main();
